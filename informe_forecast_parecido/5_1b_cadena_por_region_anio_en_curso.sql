-- 5.1b · lo que queda de 2026 por región: la misma cadena
WITH filas AS (
    SELECT n.tr_regional_level_1 AS tr_regional_level_1,
           n.tr_regional_level_3 AS tr_regional_level_3,
           CASE WHEN f.s2_2_stage3_id IS NOT NULL THEN CAST(f.s2_2_stage3_id AS VARCHAR(200)) WHEN n.s1_4_fs_id IS NOT NULL THEN CONCAT('fs|', n.s1_4_fs_id) ELSE CONCAT('ts|', n.tr_regional_level_1) END AS composicion,
           COALESCE(n.forecast_renewed_USD, 0) AS dinero_usd,
           COALESCE(n.forecast_renewed_USD, 0) - COALESCE(n.forecast_renewed_USD_low, n.forecast_renewed_USD, 0) AS desviacion_baja_usd,
           COALESCE(n.forecast_renewed_USD_high, n.forecast_renewed_USD, 0) - COALESCE(n.forecast_renewed_USD, 0) AS desviacion_alta_usd,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_to_renew_USD_at_due, 0) ELSE 0 END AS pipeline_al_vencer_usd,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_to_renew_units_at_due, 0) ELSE 0 END AS unidades_al_vencer,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.s7_2_esperado_unidades, 0) ELSE 0 END AS unidades_esperadas,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_to_renew_units_at_due, 0) * COALESCE(n.s7_2_tasa, 0) * (1 - COALESCE(n.s7_2_tasa, 0)) ELSE 0 END AS varianza_binomial,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_to_renew_units_at_due, 0) * (COALESCE(n.s7_2_tasa, 0) - COALESCE(n.s7_2_tasa_baja, n.s7_2_tasa, 0)) ELSE 0 END AS desviacion_baja_unidades,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_to_renew_units_at_due, 0) * (COALESCE(n.s7_2_tasa_alta, n.s7_2_tasa, 0) - COALESCE(n.s7_2_tasa, 0)) ELSE 0 END AS desviacion_alta_unidades,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.s7_2_esperado_usd, 0) ELSE 0 END AS esperado_usd_pipeline,
           CASE WHEN n.forecast_status = 'forecast' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.s7_2_vencen_usd_al_vencer, 0) * COALESCE(n.s7_2_tasa, 0) ELSE 0 END AS base_uplift_usd,
           CASE WHEN n.forecast_status = 'actual' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_to_renew_units, 0) ELSE 0 END AS vencen_unidades_reales,
           CASE WHEN n.forecast_status = 'actual' AND n.forecast_universe = 'pipeline' THEN COALESCE(n.forecast_renewed_units, 0) ELSE 0 END AS renovadas_unidades_reales,
           COALESCE(n.s7_2_error_captacion_usd, 0) AS error_captacion_usd
    FROM sff_nucleo AS n
    LEFT JOIN sff_forecast_series AS f ON f.s1_4_fs_id = n.s1_4_fs_id
    WHERE n.forecast_year = 2026 AND n.forecast_status = 'forecast' AND n.origen_fila NOT IN ('hueco', 'ts_sin_resultado')
)
SELECT 0 AS orden_total,
       tr_regional_level_1,
       0 AS orden_region,
       tr_regional_level_3,
       SUM(dinero_usd) AS dinero_usd,
       SUM(dinero_usd) - SQRT(SUM(desviacion_baja_usd * desviacion_baja_usd) + SUM(error_captacion_usd) * SUM(error_captacion_usd)) AS banda_baja_usd,
       SUM(dinero_usd) + SQRT(SUM(desviacion_alta_usd * desviacion_alta_usd) + SUM(error_captacion_usd) * SUM(error_captacion_usd)) AS banda_alta_usd,
       SUM(dinero_usd) - SUM(desviacion_baja_usd) - SUM(error_captacion_usd) AS banda_lineal_baja_usd,
       SUM(dinero_usd) + SUM(desviacion_alta_usd) + SUM(error_captacion_usd) AS banda_lineal_alta_usd,
       SUM(error_captacion_usd) AS error_captacion_usd,
       SUM(pipeline_al_vencer_usd) AS pipeline_al_vencer_usd,
       SUM(unidades_al_vencer) AS unidades_al_vencer,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_prevista,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) - 1.645 * SQRT(SUM(varianza_binomial)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_binomial_baja,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) + 1.645 * SQRT(SUM(varianza_binomial)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_binomial_alta,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) - SQRT(SUM(desviacion_baja_unidades * desviacion_baja_unidades)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_framework_baja,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) + SQRT(SUM(desviacion_alta_unidades * desviacion_alta_unidades)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_framework_alta,
       SUM(esperado_usd_pipeline) / NULLIF(SUM(base_uplift_usd), 0) AS uplift,
       SUM(vencen_unidades_reales) AS vencen_unidades_reales,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) AS tasa_real,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) - 1.645 * SQRT(SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) * (1 - SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0)) / NULLIF(SUM(vencen_unidades_reales), 0)) AS tasa_real_binomial_baja,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) + 1.645 * SQRT(SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) * (1 - SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0)) / NULLIF(SUM(vencen_unidades_reales), 0)) AS tasa_real_binomial_alta
FROM (SELECT tr_regional_level_1, tr_regional_level_3, composicion,
              SUM(dinero_usd) AS dinero_usd,
              SUM(desviacion_baja_usd) AS desviacion_baja_usd,
              SUM(desviacion_alta_usd) AS desviacion_alta_usd,
              SUM(pipeline_al_vencer_usd) AS pipeline_al_vencer_usd,
              SUM(unidades_al_vencer) AS unidades_al_vencer,
              SUM(unidades_esperadas) AS unidades_esperadas,
              SUM(varianza_binomial) AS varianza_binomial,
              SUM(desviacion_baja_unidades) AS desviacion_baja_unidades,
              SUM(desviacion_alta_unidades) AS desviacion_alta_unidades,
              SUM(esperado_usd_pipeline) AS esperado_usd_pipeline,
              SUM(base_uplift_usd) AS base_uplift_usd,
              SUM(vencen_unidades_reales) AS vencen_unidades_reales,
              SUM(renovadas_unidades_reales) AS renovadas_unidades_reales,
              SUM(error_captacion_usd) AS error_captacion_usd
      FROM filas
      GROUP BY tr_regional_level_1, tr_regional_level_3, composicion) AS por_composicion
GROUP BY tr_regional_level_1, tr_regional_level_3
UNION ALL
SELECT 0 AS orden_total,
       tr_regional_level_1,
       1 AS orden_region,
       'TOTAL' AS tr_regional_level_3,
       SUM(dinero_usd) AS dinero_usd,
       SUM(dinero_usd) - SQRT(SUM(desviacion_baja_usd * desviacion_baja_usd) + SUM(error_captacion_usd) * SUM(error_captacion_usd)) AS banda_baja_usd,
       SUM(dinero_usd) + SQRT(SUM(desviacion_alta_usd * desviacion_alta_usd) + SUM(error_captacion_usd) * SUM(error_captacion_usd)) AS banda_alta_usd,
       SUM(dinero_usd) - SUM(desviacion_baja_usd) - SUM(error_captacion_usd) AS banda_lineal_baja_usd,
       SUM(dinero_usd) + SUM(desviacion_alta_usd) + SUM(error_captacion_usd) AS banda_lineal_alta_usd,
       SUM(error_captacion_usd) AS error_captacion_usd,
       SUM(pipeline_al_vencer_usd) AS pipeline_al_vencer_usd,
       SUM(unidades_al_vencer) AS unidades_al_vencer,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_prevista,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) - 1.645 * SQRT(SUM(varianza_binomial)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_binomial_baja,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) + 1.645 * SQRT(SUM(varianza_binomial)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_binomial_alta,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) - SQRT(SUM(desviacion_baja_unidades * desviacion_baja_unidades)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_framework_baja,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) + SQRT(SUM(desviacion_alta_unidades * desviacion_alta_unidades)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_framework_alta,
       SUM(esperado_usd_pipeline) / NULLIF(SUM(base_uplift_usd), 0) AS uplift,
       SUM(vencen_unidades_reales) AS vencen_unidades_reales,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) AS tasa_real,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) - 1.645 * SQRT(SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) * (1 - SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0)) / NULLIF(SUM(vencen_unidades_reales), 0)) AS tasa_real_binomial_baja,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) + 1.645 * SQRT(SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) * (1 - SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0)) / NULLIF(SUM(vencen_unidades_reales), 0)) AS tasa_real_binomial_alta
FROM (SELECT tr_regional_level_1, composicion,
              SUM(dinero_usd) AS dinero_usd,
              SUM(desviacion_baja_usd) AS desviacion_baja_usd,
              SUM(desviacion_alta_usd) AS desviacion_alta_usd,
              SUM(pipeline_al_vencer_usd) AS pipeline_al_vencer_usd,
              SUM(unidades_al_vencer) AS unidades_al_vencer,
              SUM(unidades_esperadas) AS unidades_esperadas,
              SUM(varianza_binomial) AS varianza_binomial,
              SUM(desviacion_baja_unidades) AS desviacion_baja_unidades,
              SUM(desviacion_alta_unidades) AS desviacion_alta_unidades,
              SUM(esperado_usd_pipeline) AS esperado_usd_pipeline,
              SUM(base_uplift_usd) AS base_uplift_usd,
              SUM(vencen_unidades_reales) AS vencen_unidades_reales,
              SUM(renovadas_unidades_reales) AS renovadas_unidades_reales,
              SUM(error_captacion_usd) AS error_captacion_usd
      FROM filas
      GROUP BY tr_regional_level_1, composicion) AS por_composicion
GROUP BY tr_regional_level_1
UNION ALL
SELECT 1 AS orden_total,
       'TOTAL' AS tr_regional_level_1,
       2 AS orden_region,
       'TOTAL' AS tr_regional_level_3,
       SUM(dinero_usd) AS dinero_usd,
       SUM(dinero_usd) - SQRT(SUM(desviacion_baja_usd * desviacion_baja_usd) + SUM(error_captacion_usd) * SUM(error_captacion_usd)) AS banda_baja_usd,
       SUM(dinero_usd) + SQRT(SUM(desviacion_alta_usd * desviacion_alta_usd) + SUM(error_captacion_usd) * SUM(error_captacion_usd)) AS banda_alta_usd,
       SUM(dinero_usd) - SUM(desviacion_baja_usd) - SUM(error_captacion_usd) AS banda_lineal_baja_usd,
       SUM(dinero_usd) + SUM(desviacion_alta_usd) + SUM(error_captacion_usd) AS banda_lineal_alta_usd,
       SUM(error_captacion_usd) AS error_captacion_usd,
       SUM(pipeline_al_vencer_usd) AS pipeline_al_vencer_usd,
       SUM(unidades_al_vencer) AS unidades_al_vencer,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_prevista,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) - 1.645 * SQRT(SUM(varianza_binomial)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_binomial_baja,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) + 1.645 * SQRT(SUM(varianza_binomial)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_binomial_alta,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) - SQRT(SUM(desviacion_baja_unidades * desviacion_baja_unidades)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_framework_baja,
       SUM(unidades_esperadas) / NULLIF(SUM(unidades_al_vencer), 0) + SQRT(SUM(desviacion_alta_unidades * desviacion_alta_unidades)) / NULLIF(SUM(unidades_al_vencer), 0) AS tasa_framework_alta,
       SUM(esperado_usd_pipeline) / NULLIF(SUM(base_uplift_usd), 0) AS uplift,
       SUM(vencen_unidades_reales) AS vencen_unidades_reales,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) AS tasa_real,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) - 1.645 * SQRT(SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) * (1 - SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0)) / NULLIF(SUM(vencen_unidades_reales), 0)) AS tasa_real_binomial_baja,
       SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) + 1.645 * SQRT(SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0) * (1 - SUM(renovadas_unidades_reales) / NULLIF(SUM(vencen_unidades_reales), 0)) / NULLIF(SUM(vencen_unidades_reales), 0)) AS tasa_real_binomial_alta
FROM (SELECT composicion,
              SUM(dinero_usd) AS dinero_usd,
              SUM(desviacion_baja_usd) AS desviacion_baja_usd,
              SUM(desviacion_alta_usd) AS desviacion_alta_usd,
              SUM(pipeline_al_vencer_usd) AS pipeline_al_vencer_usd,
              SUM(unidades_al_vencer) AS unidades_al_vencer,
              SUM(unidades_esperadas) AS unidades_esperadas,
              SUM(varianza_binomial) AS varianza_binomial,
              SUM(desviacion_baja_unidades) AS desviacion_baja_unidades,
              SUM(desviacion_alta_unidades) AS desviacion_alta_unidades,
              SUM(esperado_usd_pipeline) AS esperado_usd_pipeline,
              SUM(base_uplift_usd) AS base_uplift_usd,
              SUM(vencen_unidades_reales) AS vencen_unidades_reales,
              SUM(renovadas_unidades_reales) AS renovadas_unidades_reales,
              SUM(error_captacion_usd) AS error_captacion_usd
      FROM filas
      GROUP BY composicion) AS por_composicion
ORDER BY 1, 2, 3, 4;
